create table if not exists public.catalog_groups (
  id bigint generated by default as identity primary key,
  category text not null,
  subcategory text,
  created_by text not null default 'System',
  created_at timestamptz not null default now()
);

create unique index if not exists catalog_groups_unique
on public.catalog_groups (lower(category), lower(coalesce(subcategory, '')));

alter table public.catalog_groups enable row level security;

drop policy if exists "Familie darf Kategorien lesen" on public.catalog_groups;
drop policy if exists "Familie darf Kategorien eintragen" on public.catalog_groups;
drop policy if exists "Familie darf Kategorien bearbeiten" on public.catalog_groups;
drop policy if exists "Familie darf Kategorien löschen" on public.catalog_groups;

create policy "Familie darf Kategorien lesen"
on public.catalog_groups for select to anon using (true);

create policy "Familie darf Kategorien eintragen"
on public.catalog_groups for insert to anon with check (true);

create policy "Familie darf Kategorien bearbeiten"
on public.catalog_groups for update to anon using (true) with check (true);

create policy "Familie darf Kategorien löschen"
on public.catalog_groups for delete to anon using (true);


create table if not exists public.catalog_products (
  id bigint generated by default as identity primary key,
  product_name text not null,
  category text not null,
  subcategory text not null,
  created_by text not null default 'System',
  created_at timestamptz not null default now()
);

create unique index if not exists catalog_products_unique
on public.catalog_products (
  lower(product_name),
  lower(category),
  lower(subcategory)
);

alter table public.catalog_products enable row level security;

drop policy if exists "Familie darf Produkte lesen" on public.catalog_products;
drop policy if exists "Familie darf Produkte eintragen" on public.catalog_products;
drop policy if exists "Familie darf Produkte bearbeiten" on public.catalog_products;
drop policy if exists "Familie darf Produkte löschen" on public.catalog_products;

create policy "Familie darf Produkte lesen"
on public.catalog_products for select to anon using (true);

create policy "Familie darf Produkte eintragen"
on public.catalog_products for insert to anon with check (true);

create policy "Familie darf Produkte bearbeiten"
on public.catalog_products for update to anon using (true) with check (true);

create policy "Familie darf Produkte löschen"
on public.catalog_products for delete to anon using (true);

